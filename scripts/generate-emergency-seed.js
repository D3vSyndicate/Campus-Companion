// Builds the emergency contacts SQL from src/data/emergency-contacts.json.
//
// That one file is the source of truth for the built-in numbers. The app bundles it as a fallback, and
// this script turns the same file into the database migration, so the two cannot drift.
//
// After editing the JSON, run:   node scripts/generate-emergency-seed.js
// Then run   node scripts/build-setup-sql.js   to rebuild the single setup file.

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const rows = JSON.parse(fs.readFileSync(path.join(root, 'src/data/emergency-contacts.json'), 'utf8'));
const target = path.join(root, 'supabase/migrations/20260920100000_emergency_contacts.sql');

const columns = ['category', 'name', 'description', 'phone', 'available', 'sort_order'];
const quote = (value) => (value === null || value === undefined ? 'null' : `'${String(value).replace(/'/g, "''")}'`);
const values = rows.map((row) => '  (' + columns.map((column) => (column === 'sort_order' ? Number(row[column]) : quote(row[column]))).join(', ') + ')');

const sql = `-- Emergency contacts: the numbers a student calls when they need urgent help.
--
-- GENERATED by scripts/generate-emergency-seed.js from src/data/emergency-contacts.json. Edit that file and
-- run the script again, rather than editing this one.
--
-- Everyone can read them, even before signing in, because someone in trouble may not be able to log in.
-- Only coordinators and admins can change them.
--
-- It starts with the well-known national numbers. Campus numbers, such as Protection Services and student
-- wellness, are not included because they have not been confirmed: add them from Emergency contacts in
-- the coordinator or admin screens.
--
-- Depends on public.is_staff() from supabase/campus_features.sql. Run that file first.
--
-- Safe to run more than once: a number is only added if that name and number are not there yet, and
-- existing entries are never overwritten.

do $$
begin
  if to_regprocedure('public.is_staff()') is null then
    raise exception 'public.is_staff() is missing. Run supabase/campus_features.sql first, then run this file.';
  end if;
end
$$;

create table if not exists public.emergency_contacts (
  id          uuid primary key default gen_random_uuid(),
  category    text not null default 'Emergency services',
  name        text not null,
  description text,
  phone       text not null,
  available   text,           -- for example "24 hours"
  sort_order  int  not null default 100,
  is_active   boolean not null default true,
  created_at  timestamptz not null default now()
);

alter table public.emergency_contacts enable row level security;

drop policy if exists cc_read on public.emergency_contacts;
drop policy if exists cc_staff_insert on public.emergency_contacts;
drop policy if exists cc_staff_update on public.emergency_contacts;
drop policy if exists cc_staff_delete on public.emergency_contacts;

create policy cc_read on public.emergency_contacts
  for select to anon, authenticated using (is_active or public.is_staff());
create policy cc_staff_insert on public.emergency_contacts
  for insert to authenticated with check (public.is_staff());
create policy cc_staff_update on public.emergency_contacts
  for update to authenticated using (public.is_staff()) with check (public.is_staff());
create policy cc_staff_delete on public.emergency_contacts
  for delete to authenticated using (public.is_staff());

insert into public.emergency_contacts (${columns.join(', ')})
select v.*
from (values
${values.join(',\n')}
) as v(${columns.join(', ')})
where not exists (
  select 1 from public.emergency_contacts e where e.name = v.name and e.phone = v.phone
);

-- Make the new table visible to the app straight away.
notify pgrst, 'reload schema';
`;

fs.writeFileSync(target, sql.replace(/\r?\n/g, '\r\n'));
console.log(`Wrote ${rows.length} contacts to ${path.relative(root, target)}`);
