// Builds the shuttle times SQL from src/data/shuttle-schedule.json.
//
// That one file is the source of truth for the published shuttle schedule. The app bundles it as a
// fallback, and this script turns the same file into the database migration, so the two cannot drift.
//
// After editing the JSON, run:   node scripts/generate-shuttle-seed.js
// Then run   node scripts/build-setup-sql.js   to rebuild the single setup file.

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const schedule = JSON.parse(fs.readFileSync(path.join(root, 'src/data/shuttle-schedule.json'), 'utf8'));
const target = path.join(root, 'supabase/migrations/20260919150000_shuttle_times_2026.sql');

const columns = ['shift', 'route_name', 'pickup_point', 'dropoff_point', 'departure_time', 'days', 'notes'];
const quote = (value) => (value === null || value === undefined ? 'null' : `'${String(value).replace(/'/g, "''")}'`);
const values = schedule.rows.map((row) => '  (' + columns.map((column) => quote(row[column])).join(', ') + ')');

const sql = `-- Shuttle times: the real ${schedule.year} ${schedule.campus} shuttle schedule.
--
-- GENERATED by scripts/generate-shuttle-seed.js from src/data/shuttle-schedule.json. Edit that file and
-- run the script again, rather than editing this one.
--
-- Source: ${schedule.source}. Every stop, and its morning and afternoon departures, plus the night shift.
-- The schedule does not say which days the shuttles run or which way each one is heading, so the days,
-- pick-up and drop-off columns are left empty. Add them from Shuttle times in the admin screens if needed.
--
-- The shuttle_times table comes from supabase/campus_features.sql. Run that file first.
--
-- Safe to run more than once: a departure is only added if that shift, stop and time is not there yet,
-- and existing entries are never overwritten. The only thing it removes is the placeholder starter times
-- (their note says "Sample time").

do $$
begin
  if to_regclass('public.shuttle_times') is null then
    raise exception 'public.shuttle_times is missing. Run supabase/campus_features.sql first, then run this file.';
  end if;
end
$$;

-- The published schedule does not state the days, so that column must be allowed to be empty.
alter table public.shuttle_times alter column days drop not null;

-- The starter times the older setup script added were placeholders, not a timetable.
delete from public.shuttle_times where notes like 'Sample time%';

insert into public.shuttle_times (${columns.join(', ')})
select v.shift, v.route_name, v.pickup_point, v.dropoff_point, v.departure_time::time, v.days, v.notes
from (values
${values.join(',\n')}
) as v(${columns.join(', ')})
where not exists (
  select 1 from public.shuttle_times s
  where s.shift = v.shift and s.route_name = v.route_name and s.departure_time = v.departure_time::time
);

-- Make the change visible to the app straight away.
notify pgrst, 'reload schema';
`;

fs.writeFileSync(target, sql.replace(/\r?\n/g, '\r\n'));
console.log(`Wrote ${schedule.rows.length} departures to ${path.relative(root, target)}`);
