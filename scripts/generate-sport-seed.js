// Builds the Sport & gym SQL from src/data/madibaz-sport.json.
//
// That one file is the source of truth for the Madibaz Sport information. The app bundles it as a
// fallback, and this script turns the same file into the database migration, so the two cannot drift.
//
// After editing the JSON, run:   node scripts/generate-sport-seed.js
// Then run the file it writes in the Supabase SQL editor.

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const rows = JSON.parse(fs.readFileSync(path.join(root, 'src/data/madibaz-sport.json'), 'utf8'));
const target = path.join(root, 'supabase/migrations/20260919140000_sport_gym_madibaz.sql');

const columns = ['kind', 'name', 'description', 'cost', 'how_to_join', 'contact_name', 'contact_phone', 'link_url', 'sort_order'];
const quote = (value) => (value === null || value === undefined ? 'null' : `'${String(value).replace(/'/g, "''")}'`);
const values = rows.map((row) => '  (' + columns.map((column) => (column === 'sort_order' ? Number(row[column]) : quote(row[column]))).join(', ') + ')');

const sql = `-- Sport & gym: the real Madibaz Sport content.
--
-- GENERATED by scripts/generate-sport-seed.js from src/data/madibaz-sport.json. Edit that file and
-- run the script again, rather than editing this one.
--
-- The Sport & gym screen reads public.sport_recreation, which supabase/campus_features.sql creates.
-- Run that file first. This one only fills the table in. (The app also has this same information built
-- in, so the screen is never empty. Rows in the database take over as soon as there are any.)
--
-- Content comes from the Madibaz Sport pages (https://sport.mandela.ac.za), compiled on 2026-09-19:
-- the sports and their club sites, how students join, and the sport office phone numbers.
-- The source has no gym opening hours, fees or sign-up steps, so those are left empty. An admin
-- can add them from Sport & Gym in the admin screens. Confirm the details before students rely on them.
--
-- Safe to run more than once: each entry is only added if an entry of that type and name does not exist
-- yet, and existing entries are never overwritten. The only thing it removes is the unedited placeholder
-- rows whose description starts with "SAMPLE:".

do $$
begin
  if to_regclass('public.sport_recreation') is null then
    raise exception 'public.sport_recreation is missing. Run supabase/campus_features.sql first, then run this file.';
  end if;
end
$$;

-- Placeholder rows from the older setup script. The real entries below replace them.
delete from public.sport_recreation where description like 'SAMPLE:%';

insert into public.sport_recreation (${columns.join(', ')})
select v.*
from (values
${values.join(',\n')}
) as v(${columns.join(', ')})
where not exists (
  select 1 from public.sport_recreation s where s.kind = v.kind and s.name = v.name
);

-- Make the table visible to the app straight away.
notify pgrst, 'reload schema';
`;

fs.writeFileSync(target, sql.replace(/\r?\n/g, '\r\n'));
console.log(`Wrote ${rows.length} entries to ${path.relative(root, target)}`);
